import { SeoReport } from './types';

/**
 * Triggers the browser's native print dialog with print-optimized CSS
 */
export function printReport(): void {
  if (typeof window !== 'undefined') {
    window.print();
  }
}

/**
 * Generates and downloads a clean, beautifully formatted Markdown/Text SEO Audit Report
 */
export function downloadTextReport(report: SeoReport): void {
  const verifiedFindings = report.findings.filter(f => f.status === 'verified');
  const warningFindings = report.findings.filter(f => f.status === 'warning');
  const failedFindings = report.findings.filter(f => f.status === 'failed');
  const unverifiedFindings = report.findings.filter(f => f.status === 'not_available');

  const content = `# ==============================================================
# PYTRON DIGITAL — SEO WEBSITE AUDIT REPORT
# Generated by: digital.pytron.io
# ==============================================================

WEBSITE AUDITED: ${report.url}
DOMAIN:          ${report.domain}
REPORT ID:       ${report.id}
DATE GENERATED:  ${new Date(report.generatedAt).toLocaleString()}
AUDIT GRADE:     ${report.overallGrade}
OVERALL SCORE:   ${report.overallScore !== null ? `${report.overallScore} / 100` : 'N/A (Live Partial Audit)'}
OVERALL STATUS:  ${report.statusLabel}

----------------------------------------------------------------
EXECUTIVE SUMMARY
----------------------------------------------------------------
${report.executiveSummary}

----------------------------------------------------------------
CATEGORY HEALTH SCORES
----------------------------------------------------------------
• Technical SEO:           ${report.categories.technical.score !== null ? `${report.categories.technical.score}/100` : 'N/A'} [${report.categories.technical.statusText}]
• On-Page SEO:            ${report.categories.onpage.score !== null ? `${report.categories.onpage.score}/100` : 'N/A'} [${report.categories.onpage.statusText}]
• Core Performance:        ${report.categories.performance.score !== null ? `${report.categories.performance.score}/100` : 'N/A'} [${report.categories.performance.statusText}]
• Content & Structure:     ${report.categories.content.score !== null ? `${report.categories.content.score}/100` : 'N/A'} [${report.categories.content.statusText}]
• Mobile Optimization:     ${report.categories.mobile.score !== null ? `${report.categories.mobile.score}/100` : 'N/A'} [${report.categories.mobile.statusText}]
• Social & Structured:     ${report.categories.social_schema.score !== null ? `${report.categories.social_schema.score}/100` : 'N/A'} [${report.categories.social_schema.statusText}]

----------------------------------------------------------------
AUDIT FINDINGS SUMMARY (LIVE VERIFICATION)
----------------------------------------------------------------
• Verified Checks (Passed): ${report.quickStats.verifiedCount}
• Warnings (Opportunities): ${report.quickStats.warningCount}
• Failed Checks (Critical): ${report.quickStats.failedCount}
• Not Available / Pending:  ${report.quickStats.unavailableCount}
• Total Checks Executed:    ${report.quickStats.totalChecks}

----------------------------------------------------------------
1. FAILED CHECKS (CRITICAL REMEDIATION)
----------------------------------------------------------------
${failedFindings.length > 0 ? failedFindings.map((f, i) => `
[FAILED #${i + 1}] ${f.title}
Category:        ${f.category.toUpperCase()}
Status:          ${f.statusLabel}
Source:          ${f.sourceProvider.toUpperCase()}
Impact:          ${f.impact}
Summary:         ${f.description}
Recommendation:  ${f.recommendation}
${f.technicalDetails ? `Technical Info:  ${f.technicalDetails}` : ''}
`).join('\n') : 'No failed critical checks encountered.'}

----------------------------------------------------------------
2. WARNINGS & IMPROVEMENT OPPORTUNITIES
----------------------------------------------------------------
${warningFindings.length > 0 ? warningFindings.map((f, i) => `
[WARNING #${i + 1}] ${f.title}
Category:        ${f.category.toUpperCase()}
Status:          ${f.statusLabel}
Source:          ${f.sourceProvider.toUpperCase()}
Impact:          ${f.impact}
Summary:         ${f.description}
Recommendation:  ${f.recommendation}
`).join('\n') : 'No improvement warnings encountered.'}

----------------------------------------------------------------
3. VERIFIED PASSING CHECKS
----------------------------------------------------------------
${verifiedFindings.map((f, i) => `
[VERIFIED #${i + 1}] ${f.title}
Category:        ${f.category.toUpperCase()}
Status:          ${f.statusLabel}
Source:          ${f.sourceProvider.toUpperCase()}
`).join('\n')}

----------------------------------------------------------------
CORE WEB VITALS METRICS OVERVIEW (GOOGLE STANDARDS)
----------------------------------------------------------------
• Largest Contentful Paint (LCP):  ${report.webVitals.lcp.value} [${report.webVitals.lcp.status.toUpperCase()}]
• Cumulative Layout Shift (CLS):    ${report.webVitals.cls.value} [${report.webVitals.cls.status.toUpperCase()}]
• First Contentful Paint (FCP):    ${report.webVitals.fcp.value} [${report.webVitals.fcp.status.toUpperCase()}]
• Total Blocking Time (TBT):        ${report.webVitals.tbt.value} [${report.webVitals.tbt.status.toUpperCase()}]
• Speed Index:                     ${report.webVitals.speedIndex.value} [${report.webVitals.speedIndex.status.toUpperCase()}]
• Time to First Byte (TTFB):        ${report.webVitals.ttfb.value} [${report.webVitals.ttfb.status.toUpperCase()}]

==============================================================
READY TO UNLOCK DEEP ORGANIC GROWTH?
==============================================================
Your free report covers baseline fundamentals for ${report.domain}.
To obtain the complete page-by-page crawl, competitor benchmark, 
keyword revenue opportunities, and a prioritized developer action plan:

Contact Pytron Digital:
Web:     https://digital.pytron.io
Service: Tailored Organic Growth & Technical SEO Engineering
Copyright © ${new Date().getFullYear()} Pytron Digital. All rights reserved.
==============================================================
`;

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `Pytron-SEO-Report-${report.domain}-${new Date().toISOString().slice(0, 10)}.md`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Downloads raw audit data in JSON format for technical teams
 */
export function downloadJsonReport(report: SeoReport): void {
  const content = JSON.stringify(report, null, 2);
  const blob = new Blob([content], { type: 'application/json;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `Pytron-SEO-Audit-${report.domain}.json`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
