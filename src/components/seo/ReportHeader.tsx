'use client';

import React from 'react';
import { SeoReport } from '@/lib/seo/types';
import { DownloadReportButton } from './DownloadReportButton';
import { Globe, ArrowLeft, RefreshCw, Calendar, ExternalLink } from 'lucide-react';

interface ReportHeaderProps {
  report: SeoReport;
  onReset: () => void;
}

export function ReportHeader({ report, onReset }: ReportHeaderProps) {
  const formattedDate = new Date(report.generatedAt).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  return (
    <div className="bg-white rounded-3xl p-6 sm:p-8 border border-slate-200/90 shadow-subtle flex flex-col md:flex-row md:items-center justify-between gap-6">
      <div className="space-y-2">
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-[11px] font-bold uppercase tracking-wider text-brand-600 bg-brand-50 border border-brand-200 px-2.5 py-0.5 rounded-md">
            SEO Website Report
          </span>
          <span className="text-xs text-slate-400">•</span>
          <span className="text-xs text-slate-500 font-medium flex items-center gap-1">
            <Calendar className="w-3.5 h-3.5 text-slate-400" />
            {formattedDate}
          </span>
        </div>

        <div className="flex flex-wrap items-center gap-3">
          <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight flex items-center gap-2">
            <span>{report.domain}</span>
          </h1>

          <a
            href={report.url}
            target="_blank"
            rel="noopener noreferrer"
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors"
            title="Open website in new tab"
          >
            <ExternalLink className="w-4 h-4" />
          </a>
        </div>

        <p className="text-xs text-slate-500 font-medium">
          Generated by <strong className="text-slate-700 font-semibold">digital.pytron.io</strong> • Pytron Digital SEO Intelligence
        </p>
      </div>

      <div className="flex flex-wrap items-center gap-3 self-start md:self-auto">
        <button
          type="button"
          onClick={onReset}
          className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl text-xs sm:text-sm font-semibold text-slate-600 bg-slate-100 hover:bg-slate-200 hover:text-slate-900 transition-colors cursor-pointer"
        >
          <RefreshCw className="w-4 h-4 text-slate-500" />
          <span>Analyze Another URL</span>
        </button>

        <DownloadReportButton report={report} />
      </div>
    </div>
  );
}
